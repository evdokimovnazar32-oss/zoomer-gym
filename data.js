// Спроектировано как изолированный сервис: сейчас берёт из локальной базы APP_DATA.exercises,
// а в будущем эту функцию легко заменить на fetch('/api/ai-plan', ...) без переделки UI!
function generateWorkoutPlan({ goal, programType, daysPerWeek }) {
    // Настройка схемы подходов/повторений под цель
    let setsScheme = "3";
    let repsScheme = "10–12";
    let restScheme = "90 сек";

    if (goal === "strength") {
        setsScheme = "4";
        repsScheme = "6–8";
        restScheme = "120–150 сек";
    } else if (goal === "fatloss") {
        setsScheme = "3";
        repsScheme = "12–15";
        restScheme = "60–75 сек";
    } else {
        // hypertrophy (масса)
        setsScheme = "3–4";
        repsScheme = "8–12";
        restScheme = "90–120 сек";
    }

    const byMuscle = (m) => APP_DATA.exercises.filter(e => e.muscleGroup === m);
    const plan = [];

    if (programType === "FULL BODY") {
        for (let d = 1; d <= daysPerWeek; d++) {
            // Чередуем акценты в разные дни фулбади
            const chestEx = byMuscle("Грудь")[(d - 1) % byMuscle("Грудь").length];
            const backEx = byMuscle("Спина")[(d - 1) % byMuscle("Спина").length];
            const legsEx = byMuscle("Ноги")[(d - 1) % byMuscle("Ноги").length];
            const shouldersEx = byMuscle("Плечи")[0];
            const armEx = (d % 2 !== 0) ? byMuscle("Бицепс")[0] : byMuscle("Трицепс")[0];
            const coreEx = byMuscle("Пресс")[0];

            plan.push({
                dayTitle: `День ${d} — Full Body (Всё тело)`,
                items: [legsEx, chestEx, backEx, shouldersEx, armEx, coreEx].filter(Boolean).map(ex => ({
                    slug: ex.slug,
                    name: ex.name,
                    muscle: ex.muscleGroup,
                    sets: setsScheme,
                    reps: repsScheme,
                    rest: restScheme
                }))
            });
        }
    } else {
        // SPLIT
        const splitTemplates = [
            { title: "Грудь + Трицепс + Плечи", groups: ["Грудь", "Плечи", "Трицепс"] },
            { title: "Спина + Бицепс + Пресс", groups: ["Спина", "Бицепс", "Пресс"] },
            { title: "Ноги + Плечи + Пресс", groups: ["Ноги", "Плечи", "Пресс"] },
            { title: "Верх тела (Грудь + Спина + Руки)", groups: ["Грудь", "Спина", "Бицепс", "Трицепс"] },
            { title: "Низ тела и слабые зоны", groups: ["Ноги", "Плечи", "Пресс"] }
        ];

        for (let d = 1; d <= daysPerWeek; d++) {
            const tpl = splitTemplates[(d - 1) % splitTemplates.length];
            let dayExercises = [];
            tpl.groups.forEach(g => {
                dayExercises = dayExercises.concat(byMuscle(g));
            });

            plan.push({
                dayTitle: `День ${d} — Сплит: ${tpl.title}`,
                items: dayExercises.map(ex => ({
                    slug: ex.slug,
                    name: ex.name,
                    muscle: ex.muscleGroup,
                    sets: setsScheme,
                    reps: repsScheme,
                    rest: restScheme
                }))
            });
        }
    }

    return plan;
}